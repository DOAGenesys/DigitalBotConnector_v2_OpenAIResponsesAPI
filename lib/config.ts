interface Config {
  PORT: number;
  LOG_LEVEL: 'debug' | 'info' | 'warn' | 'error';
  GENESYS_CONNECTION_SECRET: string;
  OPENAI_API_KEY?: string;
  DEFAULT_OPENAI_MODEL: string;
  DEFAULT_OPENAI_REASONING_EFFORT: string;
  DEFAULT_OPENAI_TEMPERATURE: number;
  DEFAULT_OPENAI_VERBOSITY?: string;
  OPENAI_TIMEOUT_MS: number;
  PROMPT_CACHE_KEY_PREFIX?: string;
  MCP_SERVERS_CONFIG_PATH?: string;
  SESSION_STORE_TYPE: 'memory' | 'redis';
  KV_REST_API_URL?: string;
  KV_REST_API_TOKEN?: string;
  ENABLE_GENESYS_FUNCTION_TOOLS: boolean;
  GENESYS_CLIENT_ID?: string;
  GENESYS_CLIENT_SECRET?: string;
  GENESYS_REGION?: string;
  GENESYS_BASE_URL?: string;
  GENESYS_LOGIN_URL?: string;
  GENESYS_ALLOWED_DATA_ACTION_IDS?: string;
  GENESYS_TOKEN_CACHE_TTL_SECONDS: number;
  GENESYS_HTTP_TIMEOUT_MS: number;
  GENESYS_HTTP_RETRY_MAX: number;
  GENESYS_HTTP_RETRY_BACKOFF_MS: number;
  GENESYS_TOOLS_STRICT_MODE: boolean;
  MAX_GENESYS_TOOLS_PER_TURN: number;
  GENESYS_TOOL_LOOP_MAX_ITERATIONS: number;
  TOOL_OUTPUT_REDACTION_FIELDS?: string;
  GENESYS_MAX_ACTION_CALLS_PER_TURN: number;
  GENESYS_MAX_TOOL_ARGUMENT_BYTES: number;
  GENESYS_ACTIONS_PER_MINUTE: number;
}

let config: Config;

export function getConfig(): Config {
  if (!config) {
    config = {
      PORT: parseInt(process.env.PORT || '3000', 10),
      LOG_LEVEL: (process.env.LOG_LEVEL || 'info') as Config['LOG_LEVEL'],
      GENESYS_CONNECTION_SECRET: process.env.GENESYS_CONNECTION_SECRET || '',
      OPENAI_API_KEY: process.env.OPENAI_API_KEY || undefined,
      DEFAULT_OPENAI_MODEL: process.env.DEFAULT_OPENAI_MODEL || 'gpt-6.1-terra',
      DEFAULT_OPENAI_REASONING_EFFORT: process.env.DEFAULT_OPENAI_REASONING_EFFORT || 'low',
      DEFAULT_OPENAI_TEMPERATURE: parseFloat(process.env.DEFAULT_OPENAI_TEMPERATURE || '0.7'),
      DEFAULT_OPENAI_VERBOSITY: process.env.DEFAULT_OPENAI_VERBOSITY || undefined,
      OPENAI_TIMEOUT_MS: parseInt(process.env.OPENAI_TIMEOUT_MS || '25000', 10),
      PROMPT_CACHE_KEY_PREFIX: process.env.PROMPT_CACHE_KEY_PREFIX,
      MCP_SERVERS_CONFIG_PATH: process.env.MCP_SERVERS_CONFIG_PATH,
      SESSION_STORE_TYPE: (process.env.SESSION_STORE_TYPE || 'memory') as Config['SESSION_STORE_TYPE'],
      KV_REST_API_URL: process.env.KV_REST_API_URL,
      KV_REST_API_TOKEN: process.env.KV_REST_API_TOKEN,
      ENABLE_GENESYS_FUNCTION_TOOLS: (process.env.ENABLE_GENESYS_FUNCTION_TOOLS || 'true').toLowerCase() === 'true',
      GENESYS_CLIENT_ID: process.env.GENESYS_CLIENT_ID,
      GENESYS_CLIENT_SECRET: process.env.GENESYS_CLIENT_SECRET,
      GENESYS_REGION: process.env.GENESYS_REGION,
      GENESYS_BASE_URL: process.env.GENESYS_BASE_URL,
      GENESYS_LOGIN_URL: process.env.GENESYS_LOGIN_URL,
      GENESYS_ALLOWED_DATA_ACTION_IDS: process.env.GENESYS_ALLOWED_DATA_ACTION_IDS,
      GENESYS_TOKEN_CACHE_TTL_SECONDS: parseInt(process.env.GENESYS_TOKEN_CACHE_TTL_SECONDS || '3000', 10),
      GENESYS_HTTP_TIMEOUT_MS: parseInt(process.env.GENESYS_HTTP_TIMEOUT_MS || '10000', 10),
      GENESYS_HTTP_RETRY_MAX: parseInt(process.env.GENESYS_HTTP_RETRY_MAX || '3', 10),
      GENESYS_HTTP_RETRY_BACKOFF_MS: parseInt(process.env.GENESYS_HTTP_RETRY_BACKOFF_MS || '250', 10),
      GENESYS_TOOLS_STRICT_MODE: (process.env.GENESYS_TOOLS_STRICT_MODE || 'false').toLowerCase() === 'true',
      MAX_GENESYS_TOOLS_PER_TURN: parseInt(process.env.MAX_GENESYS_TOOLS_PER_TURN || '20', 10),
      GENESYS_TOOL_LOOP_MAX_ITERATIONS: parseInt(process.env.GENESYS_TOOL_LOOP_MAX_ITERATIONS || '3', 10),
      TOOL_OUTPUT_REDACTION_FIELDS: process.env.TOOL_OUTPUT_REDACTION_FIELDS,
      GENESYS_MAX_ACTION_CALLS_PER_TURN: parseInt(process.env.GENESYS_MAX_ACTION_CALLS_PER_TURN || '10', 10),
      GENESYS_MAX_TOOL_ARGUMENT_BYTES: parseInt(process.env.GENESYS_MAX_TOOL_ARGUMENT_BYTES || '16384', 10),
      GENESYS_ACTIONS_PER_MINUTE: parseInt(process.env.GENESYS_ACTIONS_PER_MINUTE || '30', 10),
    };
  }
  return config;
}
